cache.set(4, {text: 'x'.repeat(3000)});assert.equal(cache.has(4), false);assert.ok(cache.bytes <= 2000);
cache.clear();assert.equal(cache.bytes, 0);assert.equal(cache.size, 0);
assert.equal(progressView({lifecycle:'RUNNING',percent:62},'READY').text,'处理中 · 62%');
