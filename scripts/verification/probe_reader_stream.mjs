assert.equal(progressView({lifecycle:'SUCCEEDED',percent:100},'READY').hidden,true);
assert.equal(progressView(null,'PENDING').percent,0);
assert.equal(progressView({lifecycle:'RUNNING',percent:999},'READY').percent,100);
